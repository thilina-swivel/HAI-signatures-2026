#!/usr/bin/env python3
"""
Regenerates js/assets.js (shared brand images) and js/photos.js (employee photos)
as base64 data URIs, so a copied signature carries its images with it.

Run from the project root:   python3 build/embed-assets.py

  assets/              -> js/assets.js        (icons, logo, banner: shared by everyone)
  Profile photoes/     -> js/photos.js        (one entry per employee, keyed by slug)
  Profile photos full/ -> js/photos-full/*.js (one file per employee, for download)
"""
import base64, pathlib, re, struct, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MIME = {".png": "image/png", ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".gif": "image/gif"}

# How big each image is DRAWN in the signature. Artwork should be supplied at
# twice this, so it stays sharp on high-DPI screens - the signature always
# declares the 1x size in both the HTML attribute and the inline style, which is
# also what stops classic Outlook rescaling it by the system DPI.
DISPLAY = {
    "banner.jpg": (480, 70),          # full-bleed: the cover strip
    "icon-phone.png": (12, 12),
    "icon-address.png": (11, 12),
    "icon-email.png": (11, 12),
    "icon-linkedin.png": (19, 19),
    "icon-facebook.png": (19, 19),
    "icon-instagram.png": (19, 19),
    "logo-web.png": (67, 19),
    "__photo__": (117, 117),          # anything in "Profile photoes/"
}

# assets/<file> -> key used in js/assets.js
SHARED = {
    "icon-phone.png": "phone",
    "icon-address.png": "address",
    "icon-email.png": "email",        # optional - an envelope; email falls back
                                      # to the address pin until you add one
    "icon-linkedin.png": "linkedin",
    "icon-facebook.png": "facebook",
    "icon-instagram.png": "instagram",
    "logo-web.png": "website",
    "banner.jpg": "banner",
}


def dimensions(data: bytes):
    """Width/height straight out of the file header - no Pillow, no install."""
    if data[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", data[16:24])
    if data[:3] == b"GIF":
        return struct.unpack("<HH", data[6:10])
    if data[:2] == b"\xff\xd8":                      # JPEG: walk to the SOF marker
        i = 2
        while i < len(data) - 9:
            if data[i] != 0xFF:
                i += 1
                continue
            marker = data[i + 1]
            if 0xC0 <= marker <= 0xCF and marker not in (0xC4, 0xC8, 0xCC):
                h, w = struct.unpack(">HH", data[i + 5 : i + 9])
                return w, h
            i += 2 + struct.unpack(">H", data[i + 2 : i + 4])[0]
    return None


def check_size(path: pathlib.Path, data: bytes, display) -> None:
    """Warn when artwork is below 2x, or the wrong shape. Never fatal."""
    size = dimensions(data)
    if not size or not display:
        return
    w, h = size
    want_w, want_h = display[0] * 2, display[1] * 2
    if w < want_w or h < want_h:
        print(f"  ! {path.name} is {w}x{h}; supply {want_w}x{want_h} or larger "
              f"(drawn at {display[0]}x{display[1]}) - it will look soft", file=sys.stderr)
    if display[1] and abs((w / h) - (display[0] / display[1])) > 0.05 * (display[0] / display[1]):
        print(f"  ! {path.name} is {w}x{h}, but it is drawn at "
              f"{display[0]}x{display[1]} - the aspect ratio does not match, so it will squash",
              file=sys.stderr)


def data_uri(path: pathlib.Path) -> str:
    mime = MIME.get(path.suffix.lower())
    if not mime:
        raise SystemExit(f"Unsupported image type: {path}")
    return f"data:{mime};base64," + base64.b64encode(path.read_bytes()).decode()


def slug(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def write_module(out: pathlib.Path, const: str, entries: dict, doc: str) -> None:
    lines = [f"// {doc}", "// Generated by build/embed-assets.py - do not edit by hand.", ""]
    lines.append("window.HAI = window.HAI || {};")
    lines.append(f"HAI.{const} = {{")
    for key, uri in entries.items():
        lines.append(f'  "{key}":')
        lines.append(f'    "{uri}",')
    lines.append("};")
    lines.append("")
    out.write_text("\n".join(lines))
    kb = out.stat().st_size / 1024
    print(f"  {out.relative_to(ROOT)}  ({len(entries)} images, {kb:.0f} KB)")


def main() -> None:
    shared = {}
    for filename, key in SHARED.items():
        path = ROOT / "assets" / filename
        if not path.exists():
            print(f"  ! missing {path.relative_to(ROOT)} - skipped", file=sys.stderr)
            continue
        check_size(path, path.read_bytes(), DISPLAY.get(filename))
        shared[key] = data_uri(path)

    photos = {}
    photo_dir = ROOT / "Profile photoes"
    if photo_dir.is_dir():
        for path in sorted(photo_dir.iterdir()):
            if path.suffix.lower() in MIME and not path.name.startswith("."):
                check_size(path, path.read_bytes(), DISPLAY["__photo__"])
                photos[slug(path.stem)] = data_uri(path)

    print("Embedding images:")
    write_module(ROOT / "js" / "assets.js", "ASSETS", shared, "Shared humaniseAI brand images.")
    write_module(ROOT / "js" / "photos.js", "PHOTOS", photos, "Employee profile photos, keyed by photo id.")
    # Full-size originals for the "Download profile photo" button. One small
    # script each, loaded only on click: a <script> tag is the one way to pull a
    # file in when index.html is opened straight off disk, where fetch() is
    # blocked and <a download> just opens the image instead of saving it.
    full_dir = ROOT / "Profile photos full"
    out_dir = ROOT / "js" / "photos-full"
    if full_dir.is_dir():
        out_dir.mkdir(exist_ok=True)
        for old in out_dir.glob("*.js"):
            old.unlink()
        count = 0
        for path in sorted(full_dir.iterdir()):
            if path.suffix.lower() in MIME and not path.name.startswith("."):
                key = slug(path.stem)
                (out_dir / f"{key}.js").write_text(
                    "// Generated by build/embed-assets.py - do not edit by hand.\n"
                    f'HAI.onFullPhoto("{key}", "{data_uri(path)}");\n')
                count += 1
        mb = sum(f.stat().st_size for f in out_dir.glob("*.js")) / 1e6
        print(f"  {out_dir.relative_to(ROOT)}/  ({count} images, {mb:.0f} MB)")

    print("\nPhoto ids available for js/employees.js:")
    for key in photos:
        print(f'  photo: "{key}"')


if __name__ == "__main__":
    main()
